"""Generate initial migration. Future updates MUST use a new migration filename."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'supabase/data/regions'
rows = []
def add(code, name, parent, level):
    rows.append((code, name, parent, level))
for p in json.loads((SOURCE / 'mainland.json').read_text()):
    pc = p['code'].ljust(6, '0')
    add(pc, p['name'], None, 1)
    if p['code'] in ('11', '12', '31', '50'):
        cc = p['code'] + '0100'
        add(cc, p['name'], pc, 2)
        for c in p['children']:
            for d in c['children']:
                add(d['code'], d['name'], cc, 3)
        continue
    for c in p['children']:
        if '直辖县级行政区划' in c['name']:
            for d in c['children']:
                add(d['code'], d['name'], pc, 2)
            continue
        cc = c['code'].ljust(6, '0')
        add(cc, c['name'], pc, 2)
        for d in c.get('children', []):
            if len(d['code']) == 6:  # Exclude towns: Dongguan etc. have no districts.
                add(d['code'], d['name'], cc, 3)
extra = json.loads((SOURCE / 'hk-mo-tw.json').read_text())
extra['台湾省']['金门县'] = ['金城镇', '金湖镇', '金沙镇', '金宁乡', '烈屿乡', '乌丘乡']
extra['台湾省']['连江县'] = ['南竿乡', '北竿乡', '莒光乡', '东引乡']
for name, prefix, pc in [('台湾省', 'TW', '710000'), ('香港特别行政区', 'HK', '810000'), ('澳门特别行政区', 'MO', '820000')]:
    add(pc, name, None, 1)
    for i, (city, districts) in enumerate(extra[name].items(), 1):
        cc = f'{prefix}-{i:02}'  # Internal IDs, NOT official administrative codes.
        add(cc, city, pc, 2)
        for j, district in enumerate(districts, 1):
            add(f'{cc}-{j:02}', district, cc, 3)
codes = {r[0] for r in rows}
assert len(codes) == len(rows)
assert sum(r[3] == 1 for r in rows) == 34
assert all(r[2] is None or r[2] in codes for r in rows)
def sql(v):
    return 'null' if v is None else "'" + str(v).replace("'", "''") + "'"
schema = '''-- Generated by tools/build_regions.py; see supabase/data/regions/README.md.
create table public.regions (
  code text primary key,
  name text not null,
  parent_code text references public.regions(code),
  level smallint not null check (level between 1 and 3),
  active boolean not null default true,
  check ((level = 1) = (parent_code is null))
);
create index regions_parent_idx on public.regions(parent_code);
alter table public.regions enable row level security;
revoke all on public.regions from anon, authenticated;
grant select, insert, update, delete on public.regions to service_role;
-- Aggregate in SQL to avoid PostgREST's default 1000-row limit.
create function public.region_dictionary() returns jsonb
language sql stable security invoker set search_path = public as $$
  select jsonb_build_object('version', md5(coalesce(string_agg(
    code || ':' || name || ':' || coalesce(parent_code, '') || ':' || level::text,
    '|' order by code), '')), 'items', coalesce(jsonb_agg(
      jsonb_build_object('code', code, 'name', name, 'parent_code', parent_code, 'level', level)
      order by code), '[]'::jsonb))
  from public.regions where active;
$$;
revoke all on function public.region_dictionary() from public, anon, authenticated;
grant execute on function public.region_dictionary() to service_role;
alter table public.stores
  add column province_code text references public.regions(code),
  add column city_code text references public.regions(code);
-- Keep existing text addresses; no ambiguous automatic backfill.
insert into public.regions (code, name, parent_code, level) values
'''
rows.sort(key=lambda r: (r[3], r[0]))
body = ',\n'.join('(' + ', '.join(sql(v) for v in r) + ')' for r in rows) + ';\n'
(ROOT / 'supabase/migrations/202611060003_regions.sql').write_text(schema + body)
print({level: sum(r[3] == level for r in rows) for level in (1, 2, 3)})
