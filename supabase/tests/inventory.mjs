// Run: node supabase/tests/inventory.mjs /path/to/node_modules/@electric-sql/pglite/dist/index.js
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const { PGlite } = await import(pathToFileURL(process.argv[2]).href);
const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create role service_role;
create schema auth; create function auth.uid() returns uuid language sql as $$ select null::uuid $$;
create table public.stores(id uuid primary key, owner_id uuid);
insert into stores values ('00000000-0000-0000-0000-000000000001',null),('00000000-0000-0000-0000-000000000002',null);`);
for (const name of ['202611030003_inventory.sql','202611030004_inventory_documents.sql']) {
  await db.exec(readFileSync(new URL('../migrations/'+name,import.meta.url),'utf8').replace(/^\uFEFF/,''));
}
const store='00000000-0000-0000-0000-000000000001';
const other='00000000-0000-0000-0000-000000000002';
const a='10000000-0000-0000-0000-000000000001';
const b='10000000-0000-0000-0000-000000000002';
await db.query(`insert into inventory_products(id,store_id,name,unit,category) values($1,$3,'A','卷','贴膜'),($2,$3,'B','瓶','洗护')`,[a,b,store]);
let seq=0;
const id=()=>`20000000-0000-0000-0000-${String(++seq).padStart(12,'0')}`;
const payload=(lines,extra={})=>({lines,supplier:'Supplier',freight:0,date:'2026-11-03',...extra});
const save=async (doc,kind,p,post=true,revision=0,s=store)=>(await db.query('select inventory_document_save($1,$2,$3,$4,$5,$6) as d',[s,doc,kind,p,revision,post])).rows[0].d;
const stock=async p=>Number((await db.query('select stock from inventory_products where id=$1',[p])).rows[0].stock);
const first=id(), entry=payload([{id:a,quantity:2,cost:10},{id:b,quantity:3,cost:5}]);
const posted=await save(first,'in',entry);
assert.equal(posted.status,'posted'); assert.equal(Number(posted.total),35);
await save(first,'in',entry); assert.equal(await stock(a),2,'replay must not double stock');
await assert.rejects(()=>save(first,'in',payload([{id:a,quantity:1,cost:10}])) ,/document_closed/);
await save(id(),'in',payload([{id:a,quantity:1,cost:20}]));
const quote=(await db.query('select inventory_quote($1,$2,$3) as q',[store,'out',payload([{id:a,quantity:2.5}])])).rows[0].q;
assert.equal(Number(quote.total),30,'preview uses FIFO as posting does');
const out=await save(id(),'out',payload([{id:a,quantity:2.5}]));
assert.equal(Number(out.total),30,'FIFO costs 2*10 + .5*20'); assert.equal(await stock(a),.5);
await assert.rejects(()=>save(id(),'out',payload([{id:a,quantity:.25},{id:b,quantity:99}])),/insufficient_stock/);
assert.equal(await stock(a),.5,'all lines roll back on failure');
await assert.rejects(()=>save(id(),'check',payload([{id:a,quantity:1,version:0}])),/stock_changed/);
await assert.rejects(()=>save(id(),'in',payload([{id:a,quantity:1,cost:10}]),true,0,other),/product_not_found/);
await assert.rejects(()=>save(id(),'in',payload([{id:a,quantity:1,cost:10},{id:a,quantity:1,cost:10}])),/duplicate_product/);
await assert.rejects(()=>save(id(),'out',payload([{id:a,quantity:-1}])),/invalid_quantity/);
const draftId=id(); const draft=await save(draftId,'out',payload([{id:a,quantity:.25}]),false);
assert.equal(await stock(a),.5,'drafts do not move stock');
await save(draftId,'out',payload([{id:a,quantity:.2}]),false,draft.revision);
await assert.rejects(()=>save(draftId,'out',payload([{id:a,quantity:.25}]),true,draft.revision),/document_changed/);
const version=(await db.query('select version from inventory_products where id=$1',[a])).rows[0].version;
await save(id(),'check',payload([{id:a,quantity:0,version}])); assert.equal(await stock(a),0,'zero is a valid actual count');
assert.equal(Number((await db.query('select sum(quantity) as q from inventory_batches where product_id=$1',[a])).rows[0].q),0);
const read=(await db.query('select inventory_read($1) as result',[store])).rows[0].result;
assert.equal(read.items.length,2); assert.equal(Number(read.items.find(p=>p.id===b).stock_value),15);
assert.equal((await db.query('select inventory_read($1,$2) as result',[other,a])).rows[0].result.item,null);
await db.exec('set role authenticated');
await assert.rejects(()=>db.query('select inventory_document_save($1,$2,$3,$4,$5,$6)',[store,id(),'in',entry,0,true]),/permission denied/);
await assert.rejects(()=>db.exec('update inventory_products set stock=999'),/permission denied/);
await db.exec('reset role');
await db.close();
console.log('Inventory transaction tests passed: FIFO, fractional quantities, atomic rollback, replay, drafts, conflicts, tenant isolation, grants.');
