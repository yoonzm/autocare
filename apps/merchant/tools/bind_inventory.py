"""Build live templates from the checked-in design output; never edits gen/."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1] / 'lib/pages'

def calls(s, name):
    result = []
    for m in re.finditer(r'\b' + name + r'\(', s):
        start = m.start(); i = m.end(); depth = 1; quote = None
        while depth:
            c = s[i]
            if quote:
                if c == '\\': i += 2; continue
                if c == quote: quote = None
            elif c in "'\"": quote = c
            elif c == '(': depth += 1
            elif c == ')': depth -= 1
            i += 1
        result.append((start, i))
    return result

def replace_call(s, name, needle, replacement, smallest=True):
    matches = [(a,b) for a,b in calls(s,name) if needle in s[a:b]]
    a,b = sorted(matches, key=lambda v:v[1]-v[0], reverse=not smallest)[0]
    return s[:a]+replacement+s[b:]

