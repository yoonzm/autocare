from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]/'lib/pages'
def calls(s,name):
    out=[]
    for m in re.finditer(r'\b'+name+r'\(',s):
        a=m.start();i=m.end();depth=1;q=None
        while depth:
            c=s[i]
            if q:
                if c=='\\':i+=2;continue
                if c==q:q=None
            elif c in "'\"":q=c
            elif c=='(':depth+=1
            elif c==')':depth-=1
            i+=1
        out.append((a,i))
    return out
def span(s,name,*needles):
    return min([(a,b) for a,b in calls(s,name) if all(n in s[a:b] for n in needles)],key=lambda p:p[1]-p[0])
def replace(s,name,needle,value):
    a,b=span(s,name,needle);return s[:a]+value+s[b:]

